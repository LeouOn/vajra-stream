SOURCE = (
    "Original English paraphrases of the Zhou Yi (classical Chinese text, public domain), "
    "written for Vajra.Stream in 2026 and released under the project's MIT licence. Hexagram names follow common English renderings."
)


def generate():
    output_path = Path(__file__).resolve().parent.parent / "knowledge" / "iching.json"

    # Format database
    db = {"version": "1.0", "source": SOURCE, "hexagrams": []}

    for pattern, data in HEXAGRAM_DATA.items():
        num, ch, pin, eng, mean, judg, img, lines = data
        db["hexagrams"].append(
            {
                "number": num,
                "pattern": pattern,
                "name_chinese": ch,
                "name_pinyin": pin,
                "name_english": eng,
                "meaning": mean,
                "judgment": judg,
                "images": img,
                "lines": lines,
            }
        )

    # Sort by hexagram number
    db["hexagrams"].sort(key=lambda x: x["number"])

    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(db, f, indent=2, ensure_ascii=False)
    print(f"Generated {len(db['hexagrams'])} hexagrams in {output_path}")


if __name__ == "__main__":
    generate()
