from __future__ import annotations

from datetime import datetime, timedelta, timezone

import pytest

from core import earth_sky
from core.earth_sky import SUPPORTED_YEARS, EphemerisUnavailable, earth_state

EQUINOX_MAR_2026 = datetime(2026, 3, 20, 14, 46, 0, tzinfo=timezone.utc)
EQUINOX_SEP_2026 = datetime(2026, 9, 23, 0, 5, 0, tzinfo=timezone.utc)
SOLSTICE_JUN_2026 = datetime(2026, 6, 21, 8, 24, 0, tzinfo=timezone.utc)
SOLSTICE_DEC_2026 = datetime(2026, 12, 21, 20, 50, 0, tzinfo=timezone.utc)

EXPECTED_KEYS = {"at", "ephemeris", "gast_deg", "sun", "moon", "planets"}
EXPECTED_BODY_KEYS = {"id", "name", "ra_deg", "dec_deg", "lat", "lon"}
EXPECTED_PLANET_ORDER = ["mercury", "venus", "mars", "jupiter", "saturn", "uranus", "neptune", "pluto"]


def wrap180(value: float) -> float:
    return ((value + 180.0) % 360.0) - 180.0


def angdiff(a: float, b: float) -> float:
    return abs(wrap180(a - b))


class TestStructure:
    def test_key_set_types_and_planet_order(self):
        state = earth_state(EQUINOX_MAR_2026)
        assert EXPECTED_KEYS <= set(state)
        assert state["ephemeris"] == "swisseph"
        assert isinstance(state["gast_deg"], float)
        for body in [state["sun"], state["moon"], *state["planets"]]:
            assert EXPECTED_BODY_KEYS <= set(body)
            assert isinstance(body["ra_deg"], float)
        assert [p["id"] for p in state["planets"]] == EXPECTED_PLANET_ORDER
        assert state["sun"]["id"] == "sun" and state["sun"]["name"] == "Sun"
        assert state["moon"]["id"] == "moon" and state["moon"]["name"] == "Moon"

    def test_lat_equals_dec_and_lon_is_wrapped_ra_minus_gast(self):
        state = earth_state(EQUINOX_MAR_2026)
        for body in [state["sun"], state["moon"], *state["planets"]]:
            assert body["lat"] == body["dec_deg"]
            expected_lon = round(wrap180(body["ra_deg"] - state["gast_deg"]), 4)
            assert angdiff(body["lon"], expected_lon) <= 0.001

    def test_values_are_rounded_to_four_decimals(self):
        state = earth_state(EQUINOX_MAR_2026)
        for body in [state["sun"], state["moon"], *state["planets"]]:
            for key in ("ra_deg", "dec_deg", "lat", "lon"):
                assert round(body[key], 4) == body[key]
        assert round(state["gast_deg"], 4) == state["gast_deg"]


class TestTimeHandling:
    def test_naive_equals_aware_utc(self):
        naive = datetime(2027, 7, 1, 12, 0, 0)
        aware = datetime(2027, 7, 1, 12, 0, 0, tzinfo=timezone.utc)
        out_naive = earth_state(naive)
        out_aware = earth_state(aware)
        assert out_naive["at"] == out_aware["at"]  # naive normalised to UTC before serialising
        for key in ("ephemeris", "gast_deg", "sun", "moon", "planets"):
            assert out_naive[key] == out_aware[key]

    def test_aware_offsets_equal_utc_equivalents(self):
        utc = datetime(2028, 1, 15, 6, 30, 0, tzinfo=timezone.utc)
        plus14 = utc.astimezone(timezone(timedelta(hours=14)))
        minus11 = utc.astimezone(timezone(timedelta(hours=-11)))
        assert earth_state(plus14) == earth_state(utc)
        assert earth_state(minus11) == earth_state(utc)

    def test_out_of_range_raises_value_error(self):
        for bad in (
            datetime(1799, 12, 31, 23, 59, 59, tzinfo=timezone.utc),
            datetime(2201, 1, 1, tzinfo=timezone.utc),
            datetime(1700, 6, 1),
        ):
            with pytest.raises(ValueError):
                earth_state(bad)

    def test_supported_range_bounds_pass(self):
        assert earth_state(datetime(1800, 1, 1, tzinfo=timezone.utc))["ephemeris"] == "swisseph"
        assert earth_state(datetime(2200, 12, 31, 23, 0, tzinfo=timezone.utc))["ephemeris"] == "swisseph"

    def test_supported_years_constant(self):
        assert SUPPORTED_YEARS == (1800, 2200)


class TestSeasonsAndRate:
    def test_sun_declination_at_2026_equinoxes(self):
        for instant in (EQUINOX_MAR_2026, EQUINOX_SEP_2026):
            assert abs(earth_state(instant)["sun"]["dec_deg"]) <= 0.5

    def test_sun_declination_at_2026_solstices(self):
        assert abs(earth_state(SOLSTICE_JUN_2026)["sun"]["dec_deg"] - 23.44) <= 0.05
        assert abs(earth_state(SOLSTICE_DEC_2026)["sun"]["dec_deg"] + 23.44) <= 0.05

    def test_gast_advances_one_solar_day(self):
        t0 = datetime(2026, 10, 22, 0, 0, 0, tzinfo=timezone.utc)
        g0 = earth_state(t0)["gast_deg"]
        g1 = earth_state(t0 + timedelta(days=1))["gast_deg"]
        # sidtime wraps [0, 360): 360.985647 deg of advance per solar day is
        # 0.9856 deg modulo 360.
        assert abs(((g1 - g0) % 360) - 0.9856) <= 0.001


class TestEphemerisUnavailable:
    def test_missing_swisseph_raises(self, monkeypatch):
        monkeypatch.setattr(earth_sky, "swe", None)
        with pytest.raises(EphemerisUnavailable):
            earth_state(EQUINOX_MAR_2026)


