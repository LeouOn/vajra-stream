def _tolerance(band: str, body_id: str) -> float:
    if band == "inside":
        return 0.01
    return 0.02 if body_id == "sun" else 0.05


class TestOracleLiterals:
    @pytest.mark.parametrize("instant,gast,band,bodies", ORACLE_CASES)
    def test_case(self, instant: str, gast: float, band: str, bodies: list):
        dt = datetime.fromisoformat(instant.replace("Z", "+00:00"))
        state = earth_state(dt)
        assert angdiff(state["gast_deg"], gast) <= _tolerance(band, "sun")
        mine = {b["id"]: b for b in [state["sun"], state["moon"], *state["planets"]]}
        for body_id, expected in bodies:
            if expected is None:
                continue  # oracle null (Pluto outside 1950-2050): skipped, not invented
            ra, dec, lon = expected
            tol = _tolerance(band, body_id)
            got = mine[body_id]
            assert angdiff(got["ra_deg"], ra) <= tol, f"{instant} {body_id} ra"
            assert abs(got["dec_deg"] - dec) <= tol, f"{instant} {body_id} dec"
            assert angdiff(got["lon"], lon) <= tol + 0.01, f"{instant} {body_id} lon"
