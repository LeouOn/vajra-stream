@pytest.fixture(scope="module")
def calc() -> AstrologicalCalculator:
    return AstrologicalCalculator()


@pytest.fixture(scope="module")
def wheel(calc) -> AuspiciousTiming:
    return AuspiciousTiming(astrology_engine=calc)


@pytest.mark.parametrize(
    (
        "lat",
        "lon",
        "instant",
        "is_day",
        "hour_index",
        "ruler",
        "day_ruler",
        "start",
        "end",
        "sunrise",
        "sunset",
        "next_sunrise",
    ),
    CASES,
)
def test_exact_planetary_hours_matches_traditional_definition(
    calc, lat, lon, instant, is_day, hour_index, ruler, day_ruler, start, end, sunrise, sunset, next_sunrise
):
    dt = _utc(instant)
    got = calc.calculate_exact_planetary_hours(dt, (lat, lon))
    assert got.get("status") == "success", got
    assert got["is_daytime"] is is_day
    assert got["hour_index"] == hour_index
    assert got["current_planetary_hour"] == ruler
    assert got["day_planet"] == day_ruler
    got_start, got_end = _utc(got["start_time"]), _utc(got["end_time"])
    assert abs(got_start - _utc(start)) <= TOL
    assert abs(got_end - _utc(end)) <= TOL
    assert got_start <= dt < got_end


@pytest.mark.parametrize(
    (
        "lat",
        "lon",
        "instant",
        "is_day",
        "hour_index",
        "ruler",
        "day_ruler",
        "start",
        "end",
        "sunrise",
        "sunset",
        "next_sunrise",
    ),
    CASES,
)
def test_timing_wheel_slices_match_traditional_definition(
    wheel, lat, lon, instant, is_day, hour_index, ruler, day_ruler, start, end, sunrise, sunset, next_sunrise
):
    dt = _utc(instant)
    slices = wheel.get_timing_wheel_data(lat=lat, lon=lon, target_dt=dt)["hourly_slices"]
    assert len(slices) == 24
    # Day part tiles sunrise -> sunset with 12 equal hours.
    assert abs(_utc(slices[0]["start_time"]) - _utc(sunrise)) <= TOL
    assert abs(_utc(slices[11]["end_time"]) - _utc(sunset)) <= TOL
    day_unit = (_utc(sunset) - _utc(sunrise)) / 12
    for i in range(12):
        assert slices[i]["period"] == "day" and slices[i]["hour_number"] == i + 1
        assert abs(_utc(slices[i]["start_time"]) - (_utc(sunrise) + day_unit * i)) <= TOL
    # Night part tiles sunset -> next sunrise.
    assert abs(_utc(slices[12]["start_time"]) - _utc(sunset)) <= TOL
    assert abs(_utc(slices[23]["end_time"]) - _utc(next_sunrise)) <= TOL
    # Exactly one current slice, matching the traditional hour.
    currents = [s for s in slices if s.get("is_current")]
    assert len(currents) == 1
    assert currents[0]["period"] == ("day" if is_day else "night")
    assert currents[0]["hour_number"] == hour_index
    assert currents[0]["ruler"] == ruler
