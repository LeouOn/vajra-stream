/** Measured over 61 days of hourly unrounded values: 0.232 pp (backend), 0.130 pp (swisseph phase angle). */
const PP_VS_BACKEND = 0.3;
const PP_VS_PHASE_ANGLE = 0.2;

describe('moonIlluminatedFraction', () => {
  it('is 0 at the new Moon (elongation 0), whatever the place in the sky', () => {
    expect(moonIlluminatedFraction(10, 5, 10, 5)).toBe(0);
    expect(moonIlluminatedFraction(0, 0, 0, 0)).toBe(0);
    expect(moonIlluminatedFraction(300.5, -20.25, 300.5, -20.25)).toBe(0);
  });

  it('is 0.5 at both quarters (elongation 90 and 270), in right ascension or declination', () => {
    expect(moonIlluminatedFraction(0, 0, 90, 0)).toBeCloseTo(0.5, 12);
    expect(moonIlluminatedFraction(0, 0, 270, 0)).toBeCloseTo(0.5, 12);
    expect(moonIlluminatedFraction(0, 0, 0, 90)).toBeCloseTo(0.5, 12);
    // Sun (40, +10), Moon (130, 0): cos psi = sin10 sin0 + cos10 cos0 cos90 = 0, so psi = 90 exactly.
    expect(moonIlluminatedFraction(40, 10, 130, 0)).toBeCloseTo(0.5, 12);
  });

  it('is 1 at the full Moon (elongation 180, the antipode)', () => {
    expect(moonIlluminatedFraction(0, 0, 180, 0)).toBeCloseTo(1, 12);
    expect(moonIlluminatedFraction(30, 20, 210, -20)).toBeCloseTo(1, 12);
    expect(moonIlluminatedFraction(359, -23.4, 179, 23.4)).toBeCloseTo(1, 12);
  });

  it('follows (1 - cos psi) / 2 at the hand-derived elongations 60 and 120', () => {
    expect(moonIlluminatedFraction(0, 0, 60, 0)).toBeCloseTo(0.25, 12);
    expect(moonIlluminatedFraction(0, 0, 120, 0)).toBeCloseTo(0.75, 12);
  });

  it('is symmetric in the two bodies, and a whole turn of right ascension changes nothing', () => {
    expect(moonIlluminatedFraction(12.5, 7, 98.75, -11)).toBeCloseTo(moonIlluminatedFraction(98.75, -11, 12.5, 7), 14);
    expect(moonIlluminatedFraction(12.5 + 360, 7, 98.75, -11)).toBeCloseTo(moonIlluminatedFraction(12.5, 7, 98.75, -11), 12);
    expect(moonIlluminatedFraction(12.5, 7, 98.75 - 720, -11)).toBeCloseTo(moonIlluminatedFraction(12.5, 7, 98.75, -11), 12);
  });

  it('stays accurate for a tiny elongation (no cancellation): 0.01 deg gives sin^2(0.005 deg)', () => {
    const expected = Math.sin((0.005 * Math.PI) / 180) ** 2;
    expect(moonIlluminatedFraction(0, 0, 0.01, 0) / expected).toBeCloseTo(1, 6);
  });

  it('is always inside [0, 1] and never decreases from the new Moon to the full along a ray', () => {
    let previous = -1;
    for (let psi = 0; psi <= 180; psi += 0.5) {
      const k = moonIlluminatedFraction(0, 0, psi, 0);
      expect(k).toBeGreaterThanOrEqual(0);
      expect(k).toBeLessThanOrEqual(1);
      expect(k).toBeGreaterThanOrEqual(previous);
      previous = k;
    }
    for (const dec of [-90, -45, 0, 45, 90]) {
      for (let ra = 0; ra < 360; ra += 15) {
        const k = moonIlluminatedFraction(ra, dec, ra * 0.37, -dec * 0.5);
        expect(k).toBeGreaterThanOrEqual(0);
        expect(k).toBeLessThanOrEqual(1);
      }
    }
  });

  it('is NaN for a non-finite input: garbage in is visible, never a plausible phase', () => {
    expect(moonIlluminatedFraction(Number.NaN, 0, 0, 0)).toBeNaN();
    expect(moonIlluminatedFraction(0, Number.POSITIVE_INFINITY, 0, 0)).toBeNaN();
    expect(moonIlluminatedFraction(0, 0, 0, Number.NEGATIVE_INFINITY)).toBeNaN();
  });

  it('covers a whole lunation in the frozen month (the check below means something)', () => {
    expect(MONTH).toHaveLength(125);
    expect(Math.min(...MONTH.map((row) => row[4]))).toBeLessThan(1);
    expect(Math.max(...MONTH.map((row) => row[4]))).toBeGreaterThan(99);
  });

  it(`agrees with the backend's illumination_pct to ${PP_VS_BACKEND} percentage points over a month of real values`, () => {
    let worst = 0;
    for (const [sunRa, sunDec, moonRa, moonDec, backendPct] of MONTH) {
      const mine = moonIlluminatedFraction(sunRa, sunDec, moonRa, moonDec) * 100;
      worst = Math.max(worst, Math.abs(mine - backendPct));
    }
    expect(worst).toBeLessThanOrEqual(PP_VS_BACKEND);
    expect(worst).toBeGreaterThan(0.05); // the two formulas really do differ a little (ecliptic latitude); it is not a copy
  });

  it(`agrees with swisseph's phase-angle fraction to ${PP_VS_PHASE_ANGLE} percentage points over the same month`, () => {
    let worst = 0;
    for (const [sunRa, sunDec, moonRa, moonDec, , phasePct] of MONTH) {
      const mine = moonIlluminatedFraction(sunRa, sunDec, moonRa, moonDec) * 100;
      worst = Math.max(worst, Math.abs(mine - phasePct));
    }
    expect(worst).toBeLessThanOrEqual(PP_VS_PHASE_ANGLE);
  });
});

describe('moonlightPenaltyMag', () => {
  it('matches an independent implementation on the frozen grid to 1e-9 mag', () => {
    PENALTY_ALTS.forEach((alt, row) => {
      PENALTY_KS.forEach((k, col) => {
        expect(moonlightPenaltyMag(alt, k), `alt ${alt} k ${k}`).toBeCloseTo(PENALTY_TABLE[row][col], 9);
      });
    });
  });

  it('is exactly 0 at and below the horizon, for every phase (no negative zero)', () => {
    for (const alt of [-90, -45, -10, -2, -0.5, -0.001, 0]) {
      for (const k of [0, 0.1, 0.5, 1]) {
        expect(Object.is(moonlightPenaltyMag(alt, k), 0), `alt ${alt} k ${k}`).toBe(true);
      }
    }
  });

  it('is 0 for a new Moon at any altitude', () => {
    for (const alt of [1, 10, 45, 90]) expect(moonlightPenaltyMag(alt, 0)).toBe(0);
  });

  it('costs a full Moon high in the sky about 1.5-2.0 mag: a 6.5 limit falls to 4.5-5', () => {
    expect(moonlightPenaltyMag(90, 1)).toBeCloseTo(1.8, 12);
    for (const alt of [45, 60, 75, 90]) {
      const p = moonlightPenaltyMag(alt, 1);
      expect(p, `alt ${alt}`).toBeGreaterThanOrEqual(1.5);
      expect(p, `alt ${alt}`).toBeLessThanOrEqual(2.0);
      expect(6.5 - p).toBeGreaterThanOrEqual(4.5);
      expect(6.5 - p).toBeLessThanOrEqual(5.0);
    }
  });

  it('costs a quarter Moon high about 0.7-1.0 mag, the same at first and last quarter', () => {
    for (const alt of [45, 60, 90]) {
      const p = moonlightPenaltyMag(alt, 0.5);
      expect(p, `alt ${alt}`).toBeGreaterThanOrEqual(0.7);
      expect(p, `alt ${alt}`).toBeLessThanOrEqual(1.0);
    }
  });

  it('costs a thin crescent (<= 10 %) at most 0.2 mag, at every altitude', () => {
    for (let alt = 0; alt <= 90; alt += 1) {
      for (const k of [0.01, 0.05, 0.1]) {
        expect(moonlightPenaltyMag(alt, k), `alt ${alt} k ${k}`).toBeLessThanOrEqual(0.2);
      }
    }
  });

  it('saturates with altitude: most of the effect is there by 30-40 deg', () => {
    const full = moonlightPenaltyMag(90, 1);
    expect(moonlightPenaltyMag(30, 1) / full).toBeGreaterThanOrEqual(0.8);
    expect(moonlightPenaltyMag(40, 1) / full).toBeGreaterThanOrEqual(0.9);
    expect(moonlightPenaltyMag(10, 1) / full).toBeLessThan(0.5); // and it is gradual, not a switch, below that
    expect(moonlightPenaltyMag(5, 1) / full).toBeLessThan(0.25);
  });

  it('is monotone: never smaller for a higher Moon or a fuller one (a 0.5 deg x 0.02 grid)', () => {
    for (let k = 0; k <= 1.0001; k += 0.02) {
      let previous = 0;
      for (let alt = -5; alt <= 90; alt += 0.5) {
        const p = moonlightPenaltyMag(alt, k);
        expect(p, `k ${k} alt ${alt}`).toBeGreaterThanOrEqual(previous - 1e-12);
        previous = p;
      }
    }
    for (let alt = -5; alt <= 90; alt += 0.5) {
      let previous = 0;
      for (let k = 0; k <= 1.0001; k += 0.02) {
        const p = moonlightPenaltyMag(alt, k);
        expect(p, `alt ${alt} k ${k}`).toBeGreaterThanOrEqual(previous - 1e-12);
        previous = p;
      }
    }
  });

  it('is continuous: neighbouring samples differ by little, and moonrise does not pop', () => {
    for (let k = 0; k <= 1.0001; k += 0.05) {
      for (let alt = -5; alt < 90; alt += 0.05) {
        const step = Math.abs(moonlightPenaltyMag(alt + 0.05, k) - moonlightPenaltyMag(alt, k));
        expect(step, `k ${k} alt ${alt}`).toBeLessThan(0.01);
      }
    }
    for (let alt = 0; alt <= 90; alt += 0.5) {
      for (let k = 0; k < 1; k += 0.005) {
        const step = Math.abs(moonlightPenaltyMag(alt, k + 0.005) - moonlightPenaltyMag(alt, k));
        expect(step, `alt ${alt} k ${k}`).toBeLessThan(0.02);
      }
    }
    expect(moonlightPenaltyMag(0.5, 1)).toBeLessThan(0.02);
    expect(moonlightPenaltyMag(1, 1)).toBeLessThan(0.1);
  });

  it('clamps an out-of-range fraction or altitude, and treats a non-finite input as no moonlight', () => {
    expect(moonlightPenaltyMag(60, 1.7)).toBe(moonlightPenaltyMag(60, 1));
    expect(moonlightPenaltyMag(60, -0.3)).toBe(0);
    expect(moonlightPenaltyMag(120, 1)).toBe(moonlightPenaltyMag(90, 1));
    expect(moonlightPenaltyMag(Number.NaN, 1)).toBe(0);
    expect(moonlightPenaltyMag(60, Number.NaN)).toBe(0);
    expect(moonlightPenaltyMag(Number.POSITIVE_INFINITY, 1)).toBe(0);
  });
});
